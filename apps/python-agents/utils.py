# Synchronous version, as FastAPI calls are typically sync unless using async def
def get_user_from_config(config: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    if not got_supabase:
        # print("Supabase library not available.")
        return None # Silently return None if Supabase is not installed for wider usability

    supabase_url = os.getenv("NEXT_PUBLIC_SUPABASE_URL")
    # For server-side, service_role_key is often used.
    # The JS version might have been using anon_key if it was client-side logic passed to backend.
    # Let's check for both, prioritizing service role.
    supabase_key = os.getenv("SUPABASE_SERVICE_ROLE_KEY") or os.getenv("NEXT_PUBLIC_SUPABASE_ANON_KEY")

    if not supabase_url or not supabase_key:
        # print("Supabase URL or Key not configured.")
        return None

    configurable = config.get("configurable", {})
    supabase_session = configurable.get("supabase_session")
    access_token = None
    if isinstance(supabase_session, dict):
        access_token = supabase_session.get("access_token")
    elif hasattr(supabase_session, 'access_token'): # If it's an object
        access_token = supabase_session.access_token


    if not access_token:
        # print("No access token in config's supabase_session.")
        return None # This is often a valid state; not all operations require a user.

    try:
        supabase_client: Client = create_client(supabase_url, supabase_key)
        # In supabase-py v1.x, it's auth.get_user(jwt=access_token)
        # In supabase-py v2.x, it might be slightly different or use user_management
        user_response = supabase_client.auth.get_user(access_token) # For supabase-py v1.x

        if user_response and hasattr(user_response, 'user') and user_response.user:
            # Assuming user_response.user is a Pydantic model or similar
            if hasattr(user_response.user, 'dict'):
                 return user_response.user.dict()
            elif isinstance(user_response.user, dict): # if it's already a dict
                 return user_response.user
            else: # Try to convert to dict if it's some other object
                try:
                    return dict(user_response.user)
                except TypeError:
                    print(f"Could not convert supabase user object to dict: {type(user_response.user)}")
                    return None
        # print("No user found for the given access token.")
        return None
    except Exception as e:
        print(f"Error fetching user from Supabase: {e}")
        return None

