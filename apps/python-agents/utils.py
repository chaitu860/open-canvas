def is_artifact_code_content(content: Any) -> bool:
    return (
        isinstance(content, dict) and
        content.get("type") == "code"
    ) or (
        hasattr(content, "type") and
        getattr(content, "type") == "code"
    )

def is_artifact_markdown_content(content: Any) -> bool:
    return (
        isinstance(content, dict) and
        content.get("type") == "text"
    ) or (
        hasattr(content, "type") and
        getattr(content, "type") == "text"
    )

def get_artifact_content(artifact: ArtifactV3) -> Union[ArtifactCodeV3, ArtifactMarkdownV3]:
    if not artifact:
        raise ValueError("No artifact found.")

    current_content = next((c for c in artifact.contents if c.index == artifact.currentIndex), None)

    if not current_content:
        if not artifact.contents:
            raise ValueError("Artifact has no contents.")
        return artifact.contents[-1]
    return current_content

