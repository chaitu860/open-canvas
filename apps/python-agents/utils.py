def create_context_document_messages(
    config: Dict[str, Any],
    context_documents_list: List[ContextDocument]
) -> List[BaseMessage]:

    if not context_documents_list:
        return []

    model_cfg = get_model_config(config)
    model_provider = model_cfg["modelProvider"]
    model_name = model_cfg["modelName"]

    processed_doc_content: List[Union[str, Dict[str, Any]]] = [] # Allow strings or dicts

    if model_provider == "openai":
        # OpenAI expects list of text content or image URLs, etc.
        # _create_context_document_messages_openai returns List[Dict{"type":"text", "text":"..."}]
        # We need to extract the text string for HumanMessage content if it's simple text.
        # However, HumanMessage can take a list of such dicts directly.
        processed_doc_content.extend(_create_context_document_messages_openai(context_documents_list))
