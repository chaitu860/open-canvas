def get_model_from_config(
    config: Dict[str, Any],
    temperature: Optional[float] = None,
    max_tokens: Optional[int] = None,
    is_tool_calling: bool = False
) -> Optional[Any]: # Return type should be BaseChatModel from LangChain
    if init_chat_model is None:
        raise ImportError("init_chat_model could not be imported. Please check LangChain installation.")

    model_params = get_model_config(config, is_tool_calling=is_tool_calling)

    # modelConfig from the original config might contain temp/max_tokens defaults
    # These can be overridden by direct parameters to this function
    cfg_model_config: Optional[CustomModelConfig] = model_params.get("modelConfig")

    current_temp = temperature
    if current_temp is None and cfg_model_config and cfg_model_config.temperatureRange:
        current_temp = cfg_model_config.temperatureRange.get("current", 0.5)
    elif current_temp is None:
        current_temp = 0.5 # Default fallback

    current_max_tokens = max_tokens
    if current_max_tokens is None and cfg_model_config and cfg_model_config.maxTokens:
        current_max_tokens = cfg_model_config.maxTokens.get("current", 4096)
    elif current_max_tokens is None:
        current_max_tokens = 4096 # Default fallback

    # LangChain user-only model check
    if model_params["modelName"] in LANGCHAIN_USER_ONLY_MODELS:
        user = get_user_from_config(config) # Sync call
        if not user:
            raise PermissionError("Unauthorized. Cannot use LangChain user-only models without a user.")
        if not user.get("email", "").endswith("@langchain.dev"):
            raise PermissionError("Unauthorized. User email must be @langchain.dev for these models.")

    # Parameters for init_chat_model
    init_params = {
        "model_name": model_params["modelName"],
        "model_provider": model_params["modelProvider"],
    }

    if model_params["modelName"] not in TEMPERATURE_EXCLUDED_MODELS:
        init_params["temperature"] = current_temp
        init_params["max_tokens"] = current_max_tokens
    else:
        # For models that don't take temperature, they might take max_completion_tokens
        init_params["max_completion_tokens"] = current_max_tokens
        # init_params["streaming"] = False # as per original TS

    if model_params.get("baseUrl"):
        init_params["base_url"] = model_params["baseUrl"]
    if model_params.get("apiKey"):
        init_params["api_key"] = model_params["apiKey"]

    if model_params.get("azureConfig"):
        azure_cfg = model_params["azureConfig"]
        init_params.update({
            "azure_openai_api_key": azure_cfg.get("azureOpenAIApiKey"),
            "azure_openai_api_instance_name": azure_cfg.get("azureOpenAIApiInstanceName"),
            "azure_openai_api_deployment_name": azure_cfg.get("azureOpenAIApiDeploymentName"),
            "azure_openai_api_version": azure_cfg.get("azureOpenAIApiVersion"),
            "azure_openai_api_base_path": azure_cfg.get("azureOpenAIBasePath"),
        })

    # Remove None values from init_params as init_chat_model might not like them
    init_params = {k: v for k, v in init_params.items() if v is not None}

    try:
        # print(f"Initializing model with params: {init_params}")
        return init_chat_model(**init_params)
    except Exception as e:
        print(f"Error initializing chat model {model_params['modelName']}: {e}")
        raise

