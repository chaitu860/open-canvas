def get_model_config(config: Dict[str, Any], is_tool_calling: bool = False) -> Dict[str, Any]:
    configurable_dict = config.get("configurable", {})
    custom_model_name = configurable_dict.get("customModelName")
    if not custom_model_name:
        raise ValueError("Model name is missing in config.")

    model_config_obj: Optional[CustomModelConfig] = configurable_dict.get("modelConfig") # Assuming it's passed as a Pydantic model or dict

    # Azure
    if custom_model_name.startswith("azure/"):
        actual_model_name = custom_model_name.replace("azure/", "")
        if is_tool_calling and "o1" in actual_model_name: # o1 models don't support tools
            actual_model_name = "gpt-4o" # Fallback
        return {
            "modelName": actual_model_name,
            "modelProvider": "azure_openai",
            "azureConfig": {
                "azureOpenAIApiKey": os.getenv("_AZURE_OPENAI_API_KEY", ""),
                "azureOpenAIApiInstanceName": os.getenv("_AZURE_OPENAI_API_INSTANCE_NAME", ""),
                "azureOpenAIApiDeploymentName": os.getenv("_AZURE_OPENAI_API_DEPLOYMENT_NAME", ""),
                "azureOpenAIApiVersion": os.getenv("_AZURE_OPENAI_API_VERSION", "2024-08-01-preview"),
                "azureOpenAIBasePath": os.getenv("_AZURE_OPENAI_API_BASE_PATH"),
            },
            "modelConfig": model_config_obj # Pass along the original modelConfig if present
        }

    provider_config = {
        "modelName": custom_model_name,
        "modelConfig": model_config_obj
    }

    # OpenAI
    if "gpt-" in custom_model_name or "o1" in custom_model_name or "o3" in custom_model_name:
        actual_model_name = provider_config["modelName"]
        if is_tool_calling and "o1" in actual_model_name:
            actual_model_name = "gpt-4o"
        return {
            **provider_config,
            "modelName": actual_model_name,
            "modelProvider": "openai",
            "apiKey": os.getenv("OPENAI_API_KEY"),
        }
    # Anthropic
    if "claude-" in custom_model_name:
        return {
            **provider_config,
            "modelProvider": "anthropic",
            "apiKey": os.getenv("ANTHROPIC_API_KEY"),
        }
    # Fireworks
    if "fireworks/" in custom_model_name:
        actual_model_name = provider_config["modelName"]
        # Fallback for tool calling if not the specific capable model
        if is_tool_calling and actual_model_name != "accounts/fireworks/models/llama-v3p3-70b-instruct":
            actual_model_name = "accounts/fireworks/models/llama-v3p3-70b-instruct"
        return {
            **provider_config,
            "modelName": actual_model_name,
            "modelProvider": "fireworks",
            "apiKey": os.getenv("FIREWORKS_API_KEY"),
        }
    # Groq
    if custom_model_name.startswith("groq/"):
        actual_model_name = custom_model_name.replace("groq/", "")
        return {
            "modelName": actual_model_name,
            "modelProvider": "groq",
            "apiKey": os.getenv("GROQ_API_KEY"),
            "modelConfig": model_config_obj # Groq might not use modelConfig but pass for consistency
        }
    # Google GenAI
    if "gemini-" in custom_model_name:
        actual_model_name = provider_config["modelName"]
        if is_tool_calling and "thinking" in actual_model_name: # Gemini thinking does not support tools
            actual_model_name = "gemini-2.0-flash-exp" # Example fallback
        return {
            **provider_config,
            "modelName": actual_model_name,
            "modelProvider": "google-genai", # or "google_vertexai" or "gemini" depending on LangChain version
            "apiKey": os.getenv("GOOGLE_API_KEY"),
        }
    # Ollama
    if custom_model_name.startswith("ollama-"):
        return {
            "modelName": custom_model_name.replace("ollama-", ""),
            "modelProvider": "ollama",
            "baseUrl": os.getenv("OLLAMA_API_URL", "http://localhost:11434"), # host.docker.internal might not work from python server
            "modelConfig": model_config_obj
        }

    raise ValueError(f"Unknown model provider for: {custom_model_name}")


