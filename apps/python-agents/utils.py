def create_ai_message_from_web_results(web_results: List[SearchResult]) -> AIMessage:
    web_results_str_parts = []
    for i, r in enumerate(web_results):
        # Ensure metadata is present, use defaults if not. Pydantic models should handle this with Optional.
        published_date = r.metadata.publishedDate if r.metadata else "Unknown"
        author = r.metadata.author if r.metadata else "Unknown"
        title = r.metadata.title if r.metadata else "Unknown title"
        url = r.metadata.url if r.metadata else "Unknown URL"

        part = (
            f'<search-result index="{i}" publishedDate="{published_date}" author="{author}">\n'
            f'  [{title}]({url})\n'
            f'  {r.page_content}\n'
            f'</search-result>'
        )
        web_results_str_parts.append(part)

    web_results_str = "\n\n".join(web_results_str_parts)
    content = f"Here is some additional context I found from searching the web. This may be useful:\n\n{web_results_str}"

    return AIMessage(
        content=content,
        # id=f"web-search-results-{uuid.uuid4()}", # In LangChain AIMessage id is not a standard param in constructor
        additional_kwargs={
            OC_WEB_SEARCH_RESULTS_MESSAGE_KEY: True,
            "webSearchResults": [res.dict(exclude_none=True) for res in web_results], # Store Pydantic as dict
            "webSearchStatus": "done",
        }
    )

