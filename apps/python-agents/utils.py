def format_artifact_content(
    content: Union[ArtifactMarkdownV3, ArtifactCodeV3],
    shorten_content: bool = False
) -> str:
    artifact_text: str
    if isinstance(content, ArtifactCodeV3): # Or use is_artifact_code_content
        artifact_text = content.code[:500] if shorten_content else content.code
    elif isinstance(content, ArtifactMarkdownV3): # Or use is_artifact_markdown_content
        artifact_text = content.fullMarkdown[:500] if shorten_content else content.fullMarkdown
    else:
        raise TypeError("Invalid content type for formatting.")

    return f"Title: {content.title}\nArtifact type: {content.type}\nContent: {artifact_text}"

def format_artifact_content_with_template(
    template: str,
    content: Union[ArtifactMarkdownV3, ArtifactCodeV3],
    shorten_content: bool = False
) -> str:
    formatted_artifact = format_artifact_content(content, shorten_content)
    return template.replace("{artifact}", formatted_artifact)

def get_string_from_content(message_content: Union[str, List[Dict[str, Any]]]) -> str:
    if isinstance(message_content, str):
        return message_content

    # Assuming content is a list of parts, e.g. from AIMessage.content
    # [{'type': 'text', 'text': 'Hello'}]
    text_parts = []
    for part in message_content:
        if isinstance(part, dict) and part.get("type") == "text" and "text" in part:
            text_parts.append(part["text"])
    return "\n".join(text_parts)


def convert_pdf_to_text(base64_pdf: str) -> str:
    try:
        cleaned_base64 = clean_base64(base64_pdf)
        pdf_buffer = BytesIO(base64.b64decode(cleaned_base64))
        reader = PdfReader(pdf_buffer)
        text_parts = [page.extract_text() for page in reader.pages if page.extract_text()]
        return "\n".join(text_parts)
    except Exception as e:
        print(f"Error converting PDF to text: {e}")
        raise

