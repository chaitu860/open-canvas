def extract_thinking_and_response_tokens(text: str) -> Dict[str, str]:
    think_start_tag = "<think>"
    think_end_tag = "</think>"

    start_index = text.find(think_start_tag)

    if start_index == -1:
        return {"thinking": "", "response": text.strip()}

    after_start_tag = text[start_index + len(think_start_tag):]
    end_index = after_start_tag.find(think_end_tag)

    if end_index == -1: # No closing tag
        return {
            "thinking": after_start_tag.strip(),
            "response": text[:start_index].strip()
        }

    thinking_content = after_start_tag[:end_index].strip()
    response_content = (text[:start_index] + after_start_tag[end_index + len(think_end_tag):]).strip()

    return {"thinking": thinking_content, "response": response_content}
