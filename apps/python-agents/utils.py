# Changed from async def to def as Python PDF processing is sync
def _create_context_document_messages_anthropic(documents: List[ContextDocument], native_pdf_support: bool) -> List[Dict[str, Any]]:
    messages = []
    for doc in documents:
        if doc.type == "application/pdf" and native_pdf_support:
            messages.append(_create_context_document_messages_anthropic_native(doc.data, doc.type))
        else:
            text = ""
            if doc.type == "application/pdf" and not native_pdf_support:
                text = convert_pdf_to_text(doc.data)
            elif doc.type.startswith("text/") or doc.type == "text":
                text = base64.b64decode(clean_base64(doc.data)).decode('utf-8') if doc.type.startswith("text/") else doc.data
            else:
                print(f"Unsupported document type for Anthropic context: {doc.type}")
                continue
            messages.append({"type": "text", "text": text})
    return messages

def _create_context_document_messages_gemini(documents: List[ContextDocument]) -> List[Dict[str, Any]]:
    gemini_parts = []
    for doc in documents:
        if doc.type == "application/pdf":
            # Corrected structure for Gemini inline_data
            gemini_parts.append({
                "inline_data": {
                    "mime_type": doc.type,
                    "data": clean_base64(doc.data)
                }
            })
        elif doc.type.startswith("text/") or doc.type == "text":
            text = base64.b64decode(clean_base64(doc.data)).decode('utf-8') if doc.type.startswith("text/") else doc.data
            gemini_parts.append({"text": text})
        else:
            print(f"Unsupported document type for Gemini context: {doc.type}")
            continue
    return gemini_parts

